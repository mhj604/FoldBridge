#!/usr/bin/env python3
"""Generate native Android/watchOS language resources from the shared catalog."""
from pathlib import Path
import hashlib
import json
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parent.parent
catalog=json.loads((ROOT/'localization/en.json').read_text())
quote=lambda value:json.dumps(value,ensure_ascii=False)
name=lambda key:'text_'+hashlib.sha256(key.encode()).hexdigest()[:16]
for folder,english in [('values',True),('values-en',True),('values-ko',False)]:
    resources=ET.Element('resources')
    for key,value in sorted(catalog.items()):
        text=value if english else key
        text=text.replace('\\','\\\\').replace('"','\\"').replace("'","\\'").replace('\n','\\n')
        ET.SubElement(resources,'string',{'name':name(key),'formatted':'false'}).text='"'+text+'"'
    ET.SubElement(resources,'string',{'name':'notification_listener_label'}).text='FoldBridge Local notifications' if english else 'FoldBridge Local 알림 전달'
    target=ROOT/'android/app/src/main/res'/folder/'strings.xml'
    target.parent.mkdir(parents=True,exist_ok=True);ET.indent(resources)
    ET.ElementTree(resources).write(target,encoding='utf-8',xml_declaration=True)
entries=',\n'.join('        Map.entry('+quote(k)+','+quote(name(k))+')' for k in sorted(catalog))
java='''// Generated by tools/generate-localization.py. Edit localization/en.json.
package dev.foldbridge;
import android.content.Context;
import java.util.Map;
final class I18n {
    private static final Map<String,String> KEYS=Map.ofEntries(
ENTRIES
    );
    static String t(Context context,String value) {
        String name=KEYS.get(value);
        if(name!=null) {
            int id=context.getResources().getIdentifier(name,"string",context.getPackageName());
            return id==0?value:context.getString(id);
        }
        // Status messages can append a BLE error number. Localize just that prefix.
        for(var entry:KEYS.entrySet())if(entry.getKey().endsWith(": ")&&value.startsWith(entry.getKey())) {
            return t(context,entry.getKey())+value.substring(entry.getKey().length());
        }
        return value;
    }
}
'''.replace('ENTRIES',entries)
(ROOT/'android/app/src/main/java/dev/foldbridge/I18n.java').write_text(java)
for code in ['ko','en']:
    target=ROOT/'watch/FoldBridge'/f'{code}.lproj';target.mkdir(exist_ok=True)
    (target/'Localizable.strings').write_text('// Generated from localization/en.json.\n'+'\n'.join(f'{quote(k)} = {quote(v if code=="en" else k)};' for k,v in sorted(catalog.items()))+'\n')
    privacy={
      'NSBluetoothAlwaysUsageDescription':('갤럭시 휴대폰의 알림을 받기 위해 블루투스를 사용합니다.','Bluetooth is used to receive notifications from your Galaxy phone.'),
      'NSLocationWhenInUseUsageDescription':('선택한 위치 기반 연결 유지 모드에서 백그라운드 실행을 시도하기 위해 위치 업데이트를 사용합니다. 위치 좌표는 저장하거나 전송하지 않습니다.','Location updates help request background runtime for the optional keep connection mode. Coordinates are never stored or sent.')
    }
    (target/'InfoPlist.strings').write_text('\n'.join(f'{quote(k)} = {quote(v[code=="en"])};' for k,v in privacy.items())+'\n')
print('Generated Android and watchOS Korean/English resources.')
